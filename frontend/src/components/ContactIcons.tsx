// 历史/异常值兜底为通用聊天图标
export function getContactIcon(key: string): ContactIcon {
  return CONTACT_ICONS[key] ?? ChatCircleDots
}

// 渠道名与 icon 成对：B 端不再单独填渠道，选中选项即同时得到名称与图标
export function contactLabel(key: string): string {
  return CONTACT_ICON_OPTIONS.find((o) => o.value === key)?.label ?? key
}

